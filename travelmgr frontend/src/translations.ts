export const getTranslation = (key: string, lang: string = 'en', params?: Record<string, any>): string => {
  let translation = translations[lang as keyof typeof translations]?.[key as keyof typeof translations.en] || 
                   translations.en[key as keyof typeof translations.en] || 
                   key;
  
  if (params) {
    Object.keys(params).forEach(param => {
      translation = translation.replace(`{${param}}`, params[param]);
    });
  }
  
  return translation;
};

